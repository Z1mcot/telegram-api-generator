import java.io.File

val BASIC_JSON_TYPES_IN_CPP: Set<String> = setOf(
    "std::int64_t",
    "bool",
    "std::string",
    "double",
    "long long"
)

private val CPP_BASE_INCLUDES = listOf(
    "#include <cstdint>",
    "#include <optional>",
    "#include <string>",
    "#include <vector>",
    "#include <memory>",
    "#include <nlohmann/json.hpp>",
