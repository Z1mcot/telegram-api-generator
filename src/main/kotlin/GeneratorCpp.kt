private fun DocType.toCppFile(
    customTypeNames: Set<String>,
): CppModelFile {
    val superType = TelegramType.from(name).superType
    val superTypeName = superType?.name ?: "TelegramModel"

    // Header: forward declare pointer types, include base class and value types
    val pointerTypes = collectPointerTypes(docFields, name, customTypeNames)
    val valueTypes = collectValueTypes(docFields, name, customTypeNames)
    val vectorElementTypes = collectVectorElementTypes(docFields, name, customTypeNames)

    val forwardDeclarations = emptyList<String>()

    val headerIncludes = buildList {
        addAll(CPP_BASE_INCLUDES)
        add("#include \"types/$superTypeName.hpp\"")
        addAll(valueTypes.map { "#include \"types/$it.hpp\"" })
        addAll(vectorElementTypes.map { "#include \"types/$it.hpp\"" })
        addAll(pointerTypes.map { "#include \"types/$it.hpp\"" })
    }

    val headerBody = buildString {
        appendLine(toCppDoc().trimEnd())
        appendLine(toCppStructDeclaration().trimEnd())
    }

    // Source: include all full definitions and implement to_json()
    val sourceIncludes = pointerTypes.map { "#include \"types/$it.hpp\"" } +
        listOf("#include <nlohmann/json.hpp>")

    val sourceBody = buildString {
        appendLine(toCppStructImplementation())
    }

    return CppModelFile(
        name = name,
        category = CppFileCategory.TYPE,
        headerContent = buildCppHeader(
            forwardDeclarations = forwardDeclarations,
            includes = headerIncludes,
            body = headerBody
        ),
        sourceContent = buildCppSource(
            headerName = name,
            category = CppFileCategory.TYPE,
            includes = sourceIncludes,
            body = sourceBody
        )
    )
}

private fun DocMethod.toCppRequestStructDeclaration() = buildString {
    val structName = requestStructName()
    appendLine("struct $structName {")
    appendLine("    typedef std::shared_ptr<$structName> Ptr;")
    if (docParameters.isEmpty()) {
        appendLine("    // Empty struct")
    } else {
        docParameters.forEachIndexed { index, parameter ->
            val fieldName = parameter.cppFieldName()
            val comment = parameter.description.cleanHtml().takeIf { it.isNotBlank() }
            if (comment != null) {
                appendLine("    // ${comment.replace("\n", " ")}")
            }

            val fieldType = parameter.toCppFieldType(null)
            appendLine("    $fieldType $fieldName;")

            if (index != docParameters.lastIndex) appendLine()
        }
    }
    append("};")

    appendLine()
    appendLine("void to_json(json& j, const $structName& value);")
    appendLine("void from_json(const json& j, $structName& value);")
}

private fun generateSerialization(name: String, fields: Map<String, String>) = buildString {
    appendLine("void to_json(json& j, const $name& value) {")
    if (fields.isEmpty()) {
        appendLine("    j = json{};")
    } else {
        appendLine("    j = json{")
        val properties = fields.keys.joinToString(separator = ",\n") { key ->
            val parameterName = fields[key]
            "        {\"$key\", value.$parameterName}"
        }
        appendLine(properties)
        appendLine("    };")
    }
    appendLine("}")
    appendLine()
    appendLine("void from_json(const json& j, $name& value) {")
    if (fields.isNotEmpty()) {
        fields.forEach { (jsonName, cppName) ->
            appendLine("    if (j.contains(\"$jsonName\")) {")
            appendLine("        j.at(\"$jsonName\").get_to(value.$cppName);")
            appendLine("    }")
        }
    }
    appendLine("}")
}

private fun DocMethod.toCppRequestStructImplementation()
    = generateSerialization(
    requestStructName(),
    docParameters.associate { parameter ->
        parameter.name to parameter.cppFieldName()
    }
)

private fun DocMethod.toCppRequestFile(
    customTypeNames: Set<String>
): CppModelFile {
    val structName = requestStructName()

    val pointerTypes = collectPointerTypesFromParameters(docParameters, structName, customTypeNames)
    val valueTypes = collectValueTypesFromParameters(docParameters, structName, customTypeNames)
    val vectorElementTypes = collectVectorElementTypesFromParameters(docParameters, structName, customTypeNames)

    val forwardDeclarations = emptyList<String>()
    val headerIncludes = buildList {
        addAll(CPP_BASE_INCLUDES)
        addAll(valueTypes.map { "#include \"types/$it.hpp\"" })
        addAll(vectorElementTypes.map { "#include \"types/$it.hpp\"" })
        addAll(pointerTypes.map { "#include \"types/$it.hpp\"" })
    }

    val headerBody = buildString {
        appendLine(toCppDoc(showReturn = false))
        appendLine(toCppRequestStructDeclaration().trimEnd())
    }

    val sourceIncludes = pointerTypes.map { "#include \"types/$it.hpp\"" } +
        valueTypes.map { "#include \"types/$it.hpp\"" } +
        vectorElementTypes.map { "#include \"types/$it.hpp\"" } +
        listOf("#include <nlohmann/json.hpp>")

    val sourceBody = toCppRequestStructImplementation()

    return CppModelFile(
        name = structName,
        category = CppFileCategory.REQUEST,
        headerContent = buildCppHeader(
            forwardDeclarations = forwardDeclarations,
            includes = headerIncludes.distinct(),
            body = headerBody
        ),
        sourceContent = buildCppSource(
            headerName = structName,
            category = CppFileCategory.REQUEST,
            includes = sourceIncludes.distinct(),
            body = sourceBody
        )
    )
}

private fun List<DocSection>.toCppModelFiles(): List<CppModelFile> {
    val docTypes = sortedDocTypes()
    val docTypeNames = docTypes.map { it.docType.name }.toSet()

    val requestStructNames = flatMap { section ->
        section.docMethods
            .filter { it.docParameters.isNotEmpty() }
            .map { it.requestStructName() }
    }.toSet()

    val superTypeNames = TelegramType.allSuper.map { it.name }.toSet()

    val customTypeNames = docTypeNames + requestStructNames + superTypeNames + setOf("TelegramModel")

    val files = mutableListOf<CppModelFile>()
    files += generateTelegramModelFile()
    files += generateFileTools()
    files += generateInputFileClassFile()
    files += generateTelegramValueClassFiles()
    files += generateSuperTypeFiles()
    files += docTypes.map { it.docType.toCppFile(customTypeNames) }
    files += flatMap { section ->
        section.docMethods.map { it.toCppRequestFile(customTypeNames) }
    }

    return files
}

fun List<DocSection>.writeCppFiles(outputDir: File) {
    if (outputDir.exists()) {
        outputDir.deleteRecursively()
    }

    val includeDir = File(outputDir, "include")
    val srcDir = File(outputDir, "src")
    val includeTypesDir = File(includeDir, "types")
    val srcTypesDir = File(srcDir, "types")
    val includeRequestsDir = File(includeDir, "requests")
    val srcRequestsDir = File(srcDir, "requests")
    val includeToolsDir = File(includeDir, "tools")
    val srcToolsDir = File(srcDir, "tools")


    listOf(includeTypesDir, srcTypesDir, includeRequestsDir, srcRequestsDir, includeToolsDir, srcToolsDir).forEach { it.mkdirs() }

    val files = toCppModelFiles()
    files.forEach { file ->
        val (headerDir, sourceDir) = when (file.category) {
            CppFileCategory.TYPE -> includeTypesDir to srcTypesDir
            CppFileCategory.REQUEST -> includeRequestsDir to srcRequestsDir
            CppFileCategory.TOOLS -> includeToolsDir to srcToolsDir
        }
        File(headerDir, "${file.name}.hpp").writeText(file.headerContent)
        if (file.sourceContent != null) {
            File(sourceDir, "${file.name}.cpp").writeText(file.sourceContent)
        }
    }

    // Write client files
    File(includeDir, "HttpClient.hpp").writeText(toHttpClientHeader())
    File(srcDir, "HttpClient.cpp").writeText(toHttpClientSource())
    File(includeDir, "Api.hpp").writeText(toApiHeader())
    File(srcDir, "Api.cpp").writeText(toApiSource())
    File(includeDir, "LongPoll.hpp").writeText(toLongPollHeader())
    File(srcDir, "LongPoll.cpp").writeText(toLongPollSource())

    // Generate CMakeLists.txt
    File(outputDir, "CMakeLists.txt").writeText(generateCppCMakeLists(files))
}

