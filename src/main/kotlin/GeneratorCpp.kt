    type.toCppTypeWithValueClasses(className, name, circularTypes)

private fun TelegramType.toCppTypeWithValueClasses(
    className: String?,
    propertyName: String?,
    circularTypes: Set<String> = emptySet()
): String {
    return when (this) {
        is TelegramType.ListType<*> -> "std::vector<${elementType.toCppTypeWithValueClasses(className, propertyName, circularTypes)}>"
        is TelegramType.Declared -> {
            // If this declared type participates in a circular include with current class, use WeakPtr
            if (name in circularTypes && name != className) {
                "std::shared_ptr<${name}>"
            } else {
                "${name}::Ptr"
            }
        }
        else -> when {
            propertyName == null -> toCppTypeNoValueClasses()
            className == "User" && propertyName == "id" -> "std::int64_t"
            propertyName == "user_id" -> "std::int64_t"
            className == "Chat" && propertyName == "id" -> "std::int64_t"
            className == "ChatFullInfo" && propertyName == "id" -> "std::int64_t"
            propertyName == "chat_id" -> "std::int64_t"
            propertyName.endsWith("_chat_id") -> "std::int64_t"
            propertyName == "message_id" -> "std::int64_t"
            propertyName == "message_ids" -> "std::int64_t"
            className == "BusinessConnection" && propertyName == "id" -> "std::string"
            propertyName == "business_connection_id" -> "std::string"
            propertyName == "message_thread_id" -> "std::int64_t"
            propertyName == "message_effect_id" -> "std::string"
            propertyName == "parse_mode" -> "std::string"
            else -> toCppTypeNoValueClasses()
        }
    }
}

private fun getDefaultValueForCppType(type: String, methodName: String? = null, propertyName: String? = null): String {

    if (methodName == "sendPoll" && propertyName == "is_anonymous") {
        return " = true"
    }

    if (propertyName == "revoke_messages") {
        return " = true"
    }

    if (propertyName == "correct_option_id") {
        return " = -1"
    }

    if (propertyName == "limit") {
        return " = 100"
    }

    if (propertyName == "maxConnections") {
        return " = 40"
    }

    return when (type) {
        "std::int64_t" -> " = 0"
        "double" -> " = 0.0"
        "bool" -> " = false"
        "std::string" -> " = \"\""
        else -> when {
            type.startsWith("std::") -> " = $type()" 
            else -> " = nullptr" 
        }
    }
}

