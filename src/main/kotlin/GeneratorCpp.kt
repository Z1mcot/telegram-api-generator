private fun DocType.toCppFile(
    customTypeNames: Set<String>,
): CppModelFile {
    val superType = TelegramType.from(name).superType
    val superTypeName = superType?.name ?: "TelegramModel"

    // Header: forward declare pointer types, include base class and value types
    val pointerTypes = collectPointerTypesFromFields(docFields, name, customTypeNames)
    val valueTypes = collectValueTypesFromFields(docFields, name)
    val vectorElementTypes = collectVectorElementTypesFromFields(docFields, name, customTypeNames)

    val customIncludes = buildList {
        addAll(valueTypes)
        addAll(vectorElementTypes)
        addAll(pointerTypes)
    }.toSet()

    // detect circular includes: if an included type already includes this type, forward-declare instead
    val circularTypes = customIncludes.filter { included -> cppIncludesMap[included]?.contains(name) == true }.toSet()

    val forwardDeclarations = circularTypes.map { included -> "struct $included;" }

    val headerIncludes = buildList {
        addAll(CPP_BASE_INCLUDES)
        add("#include \"types/$superTypeName.hpp\"")
        // include only non-circular custom types
        addAll((customIncludes - circularTypes).map { "#include \"types/$it.hpp\"" })
    }

    val headerBody = buildString {
        appendLine(toCppDoc().trimEnd())
        appendLine(toCppStructDeclaration(circularTypes).trimEnd())
    }

    // Source: include all full definitions and implement to_json()
    val sourceIncludes = pointerTypes.map { "#include \"types/$it.hpp\"" } +
        listOf("#include <nlohmann/json.hpp>")

    val sourceBody = buildString {
        appendLine(toCppStructImplementation())
    }

    return CppModelFile(
        name = name,
        category = CppFileCategory.TYPE,
        headerContent = buildCppHeader(
            forwardDeclarations = forwardDeclarations,
            includes = headerIncludes,
            body = headerBody
        ),
        sourceContent = buildCppSource(
            headerName = name,
            category = CppFileCategory.TYPE,
            includes = sourceIncludes,
            body = sourceBody
        )
    ).also {
        // Update includes map for this generated type: store names of included custom types (excluding forward-declared circulars)
        val includesForMap = (customIncludes - circularTypes).toMutableSet()
        if (superTypeName != "TelegramModel") includesForMap.add(superTypeName)
        cppIncludesMap[name] = includesForMap
    }
}

private fun DocMethod.toCppRequestStructDeclaration(circularTypes: Set<String> = emptySet()) = buildString {
    val structName = requestStructName()
    appendLine("struct $structName {")
    appendLine("    typedef std::shared_ptr<$structName> Ptr;")
    if (docParameters.isEmpty()) {
        appendLine("    // Empty struct")
    } else {
        docParameters.forEachIndexed { index, parameter ->
            val fieldName = parameter.cppFieldName()
            val comment = parameter.description.cleanHtml().takeIf { it.isNotBlank() }
            if (comment != null) {
                appendLine("    // ${comment.replace("\n", " ")}")
            }

            val fieldType = parameter.toCppFieldType(null, circularTypes)
            val fieldDefaultValue = getDefaultValueForCppType(fieldType)
            appendLine("    $fieldType $fieldName$fieldDefaultValue;")

            if (index != docParameters.lastIndex) appendLine()
        }
    }
    append("};")

    appendLine()
    appendLine("void to_json(json& j, const $structName& value);")
    appendLine("void from_json(const json& j, $structName& value);")
    
    // Add multipart serialization method if this request has file uploads
    if (hasInputFileParameter()) {
        appendLine()
        appendLine("// Generate multipart form data for file uploads")
        appendLine("std::string toMultipart(const $structName& value, const std::string& boundary);")
    }
}

private fun wrapWithOptionalCheck(field: DocField, className: String, toJsonField: String): String {
    return when (field.type) {
        is TelegramType.ListType<*> -> """if (!value.${field.cppFieldName()}.empty()) { 
            $toJsonField 
        }""".trimIndent()
        
        is TelegramType.Super -> """if (value.${field.cppFieldName()}) { 
            $toJsonField 
        }""".trimIndent()
        is TelegramType.Declared -> """if (value.${field.cppFieldName()}) { 
            $toJsonField 
        }""".trimIndent()

        TelegramType.Integer -> """if (value.${field.cppFieldName()} != 0) { 
            $toJsonField 
        }""".trimIndent()

        TelegramType.ParseMode,
        TelegramType.StringType -> """if (!value.${field.cppFieldName()}.empty()) { 
            $toJsonField 
        }""".trimIndent()

        TelegramType.Boolean -> """if (value.${field.cppFieldName()}) { 
            $toJsonField 
        }""".trimIndent()
        TelegramType.Float -> """if (value.${field.cppFieldName()} != 0.0) { 
            $toJsonField 
        }""".trimIndent()

        TelegramType.CallbackGame,
        TelegramType.InputFile,
        TelegramType.ForumTopicClosed,
        TelegramType.ForumTopicReopened,
        TelegramType.GeneralForumTopicHidden,
        TelegramType.GeneralForumTopicUnhidden,
        TelegramType.GiveawayCreated,
        TelegramType.VoiceChatStarted,
        TelegramType.VideoChatStarted -> """if (value.${field.cppFieldName()}) { 
            $toJsonField 
        }""".trimIndent()
        

        is TelegramType.WithAlternative -> when (field.type) {
            TelegramType.WithAlternative.InputFileOrString -> """if (!value.${field.cppFieldName()}.empty()) { 
                $toJsonField 
            }""".trimIndent()
            TelegramType.WithAlternative.IntegerOrString -> {
                if (field.toCppFieldType(className, emptySet()) == "int64_t") {
                    return """if (value.${field.cppFieldName()} != 0) { 
                                $toJsonField
                              }""".trimIndent()        
                } else {
                    return """if (!value.${field.cppFieldName()}.empty()) { 
                                $toJsonField 
                              }""".trimIndent()
                }
            }
            
        }
    }
}

private fun generateSerialization(name: String, fields: List<DocField>) = buildString {
    appendLine("void to_json(json& j, const $name& value) {")
    if (fields.isEmpty()) {
        appendLine("    j = json{};")
    } else {
        appendLine("    j = json{};")
        
        if (fields.isNotEmpty()) {
            fields.forEach { field ->
                val jsonName = field.name
                val cppName = field.cppFieldName()

                var toJsonField = "    j[\"$jsonName\"] = value.$cppName;"
                if (!field.required) {
                    toJsonField = wrapWithOptionalCheck(field, name, toJsonField)
                }

                appendLine(toJsonField)
        }
        }
    }
    appendLine("}")
    appendLine()
    appendLine("void from_json(const json& j, $name& value) {")
    if (fields.isNotEmpty()) {
        fields.forEach { field ->
            val jsonName = field.name
            val cppName = field.cppFieldName()
            appendLine("    if (j.contains(\"$jsonName\")) {")
            appendLine("        j.at(\"$jsonName\").get_to(value.$cppName);")
            appendLine("    }")
        }
    }
    appendLine("}")
}

private fun DocMethod.hasInputFileParameter(): Boolean =
    docParameters.any { it.type.containsInputFile() }

private fun DocMethod.toCppRequestStructImplementation()
    = generateSerialization(
    requestStructName(),
    docParameters
        .filter { !it.type.containsInputFile() }  // Exclude InputFile fields from serialization
        .map { parameter ->
            DocField(parameter.name, parameter.description, parameter.type, parameter.required)
        }
)

private fun DocMethod.toCppRequestFile(
    customTypeNames: Set<String>
): CppModelFile {
    val structName = requestStructName()

    val pointerTypes = collectPointerTypesFromParameters(docParameters, structName, customTypeNames)
    val valueTypes = collectValueTypesFromParameters(docParameters, structName)
    val vectorElementTypes = collectVectorElementTypesFromParameters(docParameters, structName, customTypeNames)

    val customIncludes = buildList {
        addAll(valueTypes)
        addAll(vectorElementTypes)
        addAll(pointerTypes)
    }.toSet()

    // detect circular includes for request struct: if an included type already includes this struct, forward-declare
    val circularTypes = customIncludes.filter { included -> cppIncludesMap[included]?.contains(structName) == true }.toSet()

    val forwardDeclarations = circularTypes.map { included -> "struct $included;" }

    val headerIncludes = buildList {
        addAll(CPP_BASE_INCLUDES)
        addAll((customIncludes - circularTypes).map { "#include \"types/$it.hpp\"" })
        if (hasInputFileParameter()) add("#include <string>")
    }

    val headerBody = buildString {
        appendLine(toCppDoc(showReturn = false))
        appendLine(toCppRequestStructDeclaration(circularTypes).trimEnd())
    }

    val sourceBody = buildString {
        appendLine(toCppRequestStructImplementation())
        if (hasInputFileParameter()) {
            appendLine()
            val nonFileParams = docParameters.filter { !it.type.containsInputFile() }
            val fileParams = docParameters.filter { it.type.containsInputFile() }
            
            appendLine("std::string toMultipart(const $structName& value, const std::string& boundary) {")
            appendLine("    std::string body;")
            appendLine()
            
            // Add non-file fields
            // TODO add the support of custom structures
            nonFileParams.forEach { param ->
                val fieldName = param.cppFieldName()
                val fieldType = param.toCppFieldType(null, circularTypes)
                appendLine("    // Non-file field: ${param.name}")
                appendLine("    body += \"--\" + boundary + \"\\r\\n\";")
                appendLine("    body += \"Content-Disposition: form-data; name=\\\"${param.name}\\\"\\r\\n\\r\\n\";")
                if (fieldType == "std::string") {
                    appendLine("    body += value.$fieldName + \"\\r\\n\";")
                } else if (fieldType == "bool") {
                    appendLine("    body += (value.$fieldName ? \"true\" : \"false\") + std::string(\"\\r\\n\");")
                } else if (fieldType == "std::vector<std::string>") {
                    appendLine("    for (const auto& item : value.$fieldName) {")
                    appendLine("        body += item + \"\\r\\n\";")
                    appendLine("    }")
                } else {
                    appendLine("    body += std::to_string(value.$fieldName) + \"\\r\\n\";")
                }
                appendLine()
            }
            
            // Add file fields
            fileParams.forEach { param ->
                val fieldName = param.cppFieldName()
                appendLine("    // File field: ${param.name}")
                appendLine("    if (value.$fieldName) {")
                appendLine("        body += \"--\" + boundary + \"\\r\\n\";")
                appendLine("        body += \"Content-Disposition: form-data; name=\\\"${param.name}\\\"; filename=\\\"\" + value.$fieldName->fileName + \"\\\".\\r\\n\";")
                appendLine("        body += \"Content-Type: \" + value.$fieldName->mimeType + \"\\r\\n\\r\\n\";")
                appendLine("        body += value.$fieldName->data + \"\\r\\n\";")
                appendLine("    }")
                appendLine()
            }
            
            appendLine("    body += \"--\" + boundary + \"--\\r\\n\";")
            appendLine("    return body;")
            appendLine("}")
        }
    }

    val sourceIncludes = if (hasInputFileParameter()) listOf("#include <string>") else emptyList()

    return CppModelFile(
        name = structName,
        category = CppFileCategory.REQUEST,
        headerContent = buildCppHeader(
            forwardDeclarations = forwardDeclarations,
            includes = headerIncludes.distinct(),
            body = headerBody
        ),
        sourceContent = buildCppSource(
            headerName = structName,
            category = CppFileCategory.REQUEST,
            includes = sourceIncludes,
            body = sourceBody
        )
    ).also {
        cppIncludesMap[structName] = (customIncludes - circularTypes).toMutableSet()
    }
}

private fun List<DocSection>.toCppModelFiles(): List<CppModelFile> {
    val docTypes = sortedDocTypes()
    val docTypeNames = docTypes.map { it.docType.name }.toSet()

    val requestStructNames = flatMap { section ->
        section.docMethods
            .filter { it.docParameters.isNotEmpty() }
            .map { it.requestStructName() }
    }.toSet()

    val superTypeNames = TelegramType.allSuper.map { it.name }.toSet()

    val customTypeNames = docTypeNames + requestStructNames + superTypeNames + setOf("TelegramModel")

    val files = mutableListOf<CppModelFile>()
    files += generateTelegramModelFile()
    files += generateFileTools()
    files += generateInputFileClassFile()
    files += generateTelegramNoValueClassFiles()
    files += generateSuperTypeFiles()
    files += docTypes.map { it.docType.toCppFile(customTypeNames) }
    files += flatMap { section ->
        section.docMethods.map { it.toCppRequestFile(customTypeNames) }
    }
    files += generateEventBroadcaster()
    files += generateEventHandler()
    files += generateStringTools()
    files += generateBotClass()
    files += generateHttpClient()
    files += generateLibCoroHttpClient()
    files += generateApi()
    files += generateTelegramResponse()
    files += generateWebhookService()
    files += generateLongPoll()

    return files
}

fun List<DocSection>.writeCppFiles(outputDir: File) {
    if (outputDir.exists()) {
        outputDir.deleteRecursively()
    }

    val includeDir = File(outputDir, "include")
    val srcDir = File(outputDir, "src")
    val includeTypesDir = File(includeDir, "types")
    val srcTypesDir = File(srcDir, "types")
    val includeRequestsDir = File(includeDir, "requests")
    val srcRequestsDir = File(srcDir, "requests")
    val includeToolsDir = File(includeDir, "tools")
    val srcToolsDir = File(srcDir, "tools")
    val includeNetDir = File(includeDir, "net")
    val srcNetDir = File(srcDir, "net")


    listOf(includeTypesDir, srcTypesDir, includeRequestsDir, srcRequestsDir, includeToolsDir, srcToolsDir, includeNetDir, srcNetDir).forEach { it.mkdirs() }

    val files = toCppModelFiles()
    files.forEach { file ->
        val (headerDir, sourceDir) = when (file.category) {
            CppFileCategory.TYPE -> includeTypesDir to srcTypesDir
            CppFileCategory.REQUEST -> includeRequestsDir to srcRequestsDir
            CppFileCategory.TOOLS -> includeToolsDir to srcToolsDir
            CppFileCategory.NET -> includeNetDir to srcNetDir
            CppFileCategory.ROOT -> includeDir to srcDir
        }
        File(headerDir, "${file.name}.hpp").writeText(file.headerContent)
        if (file.sourceContent != null) {
            File(sourceDir, "${file.name}.cpp").writeText(file.sourceContent)
        }
    }

    // Generate CMakeLists.txt
    File(outputDir, "CMakeLists.txt").writeText(generateCppCMakeLists(files))
}

