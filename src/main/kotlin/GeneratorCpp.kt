private fun generateTelegramModelFile(): CppModelFile {


    val headerBody = buildString {
        appendLine("""
        struct TelegramModel {
            typedef std::shared_ptr<TelegramModel> Ptr;
            
            virtual ~TelegramModel() = default;
        };
        
        
        """.trimIndent()
        )

        // Generic JSON serialization for std::shared_ptr<T> so model fields can use pointers
        appendLine("""
        template <typename T>
        void to_json(json& j, const std::shared_ptr<T>& value) {
            if (!value) {
                j = nullptr;
            } else {
                j = *value;
            }
        }

        template <typename T>
        void from_json(const json& j, std::shared_ptr<T>& value) {
            if (j.is_null()) {
                value.reset();
            } else {
                value = std::make_shared<T>(j.get<T>());
            }
        }

        template <typename T>
        void to_json(json& j, const std::weak_ptr<T>& value) {
            if (std::shared_ptr<T> locked = value.lock()) {
                j = locked;
            } else {
                j = nullptr;
            }
        }

        template <typename T>
        void from_json(const json& j, std::weak_ptr<T>& value) {
            if (j.is_null()) {
                value.reset();
            } else {
                value = std::make_shared<T>(j.get<T>());
            }
        }   
        """.trimIndent() 
        // TODO reverse for Message (now Message has weak_ptrs but it should be otherwise). Or maybe remove weak_ptr, it shouldn't lead to circular includes
        )
    }.trimEnd()

    val headerContent = buildCppHeader(
        forwardDeclarations = emptyList(),
        includes = CPP_BASE_INCLUDES,
        body = headerBody
    )
    return CppModelFile(
        name = "TelegramModel",
        category = CppFileCategory.TYPE,
        headerContent = headerContent,
        sourceContent = null
    )
}

private fun TelegramType.superTypeNameOrBase(): String =
    when (val parent = superType) {
        null -> "TelegramModel"
        else -> parent.name
    }

