        if (docParameters.isNotEmpty()) appendLine(" *")
        appendLine(" * @return ${returns.toCppType()}")
    }
    append(" */")
}

private fun DocType.toCppStructDeclaration(circularTypes: Set<String> = emptySet()) = buildString {
    val telegramType = TelegramType.from(name)
    val superTypeName = when (val superType = telegramType.superType) {
        null -> "TelegramModel"
        else -> superType.name
    }

    appendLine("struct $name : public $superTypeName {")
    appendLine("    typedef std::shared_ptr<$name> Ptr;")
    appendLine("    typedef std::weak_ptr<$name> WeakPtr;")
    appendLine()
    appendLine("    virtual ~$name() = default;")
    if (docFields.isEmpty()) {
        appendLine("    // Empty struct")
    } else {
        docFields.forEachIndexed { index, field ->
            val fieldName = field.cppFieldName()
            val comment = field.description.cleanHtml().takeIf { it.isNotBlank() }
            if (comment != null) {
                appendLine("    // ${comment.replace("\n", " ")}")
            }
            val fieldType = field.toCppFieldType(name, circularTypes)
            val defaultValue = getDefaultValueForCppType(fieldType)
            appendLine("    $fieldType $fieldName$defaultValue;")

            if (index != docFields.lastIndex) appendLine()
        }
    }
    append("};")

    appendLine()
    appendLine("void to_json(json& j, const $name& value);")
    appendLine("void from_json(const json& j, $name& value);")
}


