private fun buildCppHeader(
    forwardDeclarations: Collection<String>,
    includes: Collection<String>,
    body: String
): String = buildString {
    appendLine("// Auto-generated Telegram Bot API models for C++")
    appendLine("// Generated by telegram-api-generator. Do not edit manually.\n")
    appendLine("#pragma once")
    includes.distinct().forEach { appendLine(it) }
    appendLine()
    appendLine("namespace TgBot {")
    if (forwardDeclarations.isNotEmpty()) {
        appendLine()
        forwardDeclarations.distinct().forEach { appendLine("    $it") }
    }
    appendLine()
    if (includes.any { it.contains("nlohmann/json.hpp") }) {
        appendLine("    using json = nlohmann::json;")
        appendLine()
    }
    appendLine(withIndent(body.trimEnd()))
    appendLine("}")
}

private fun buildCppSource(
    headerName: String,
    category: CppFileCategory,
    includes: Collection<String>,
    body: String
): String = buildString {
    appendLine("// Auto-generated Telegram Bot API models for C++")
    appendLine("// Generated by telegram-api-generator. Do not edit manually.\n")
    val prefix = when (category) {
        CppFileCategory.TYPE -> "types/"
        CppFileCategory.REQUEST -> "requests/"
        CppFileCategory.TOOLS -> "tools/"
        CppFileCategory.NET -> "net/"
        CppFileCategory.ROOT -> ""
    }
    appendLine("#include \"$prefix$headerName.hpp\"")
    includes.distinct().forEach { appendLine(it) }
    appendLine()
    appendLine("namespace TgBot {")
    appendLine(withIndent(body.trimEnd()))
    appendLine("}")
}

private fun stripCppWrappers(type: String): String {
    var result = type.trim()
    var changed: Boolean
    do {
        changed = false
        if (result.startsWith("std::vector<") && result.endsWith(">")) {
            result = result.removePrefix("std::vector<").removeSuffix(">")
            changed = true
        } else if (result.endsWith("Ptr")) {
            result = result.removeSuffix("::Ptr")
            changed = true
        } else if (result.startsWith("std::weak_ptr<") && result.endsWith(">")) {
            result = result.removePrefix("std::weak_ptr<").removeSuffix(">")
            changed = true
        }
    } while (changed)
    return result
}

private fun extractCustomTypes(
    cppType: String,
    customTypeNames: Set<String>,
    currentName: String? = null
): Set<String> {
    val baseType = stripCppWrappers(cppType)
    return buildSet {
        if (baseType in customTypeNames && baseType != currentName) {
            add(baseType)
        }
    }
}

private fun collectPointerTypes(
    fieldTypes: List<String>,
    className: String?,
    customTypeNames: Set<String>
): Set<String> = fieldTypes.mapNotNull { fieldType ->
    if (fieldType.endsWith("Ptr")) {
        val baseType = stripCppWrappers(fieldType)
        if (baseType in customTypeNames && baseType != className) {
            baseType
        } else null
    } else null
}.toSet()

