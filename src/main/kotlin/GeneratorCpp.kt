         * Save file to disk.
         * @param filePath Path to a file
         * @throws exception of type std::ifstream::failure if writing fails
        */
        void write(const std::string& content, const std::string& filePath);

        }
    """.trimIndent()

    val sourceBody = """
        using namespace std;

        namespace FileTools {

        string read(const string& filePath) {
            ifstream in(filePath, ios::in | ios::binary);
            in.exceptions(ifstream::failbit | ifstream::badbit);
            ostringstream contents;
            contents << in.rdbuf();
            in.close();
            return contents.str();
        }

        void write(const string& content, const string& filePath) {
            ofstream out(filePath, ios::out | ios::binary);
            out.exceptions(ofstream::failbit | ofstream::badbit);
            out << content;
            out.close();
        }

        }
    """.trimIndent()

    val headerContent = buildCppHeader(
        forwardDeclarations = emptyList(),
        includes = listOf("#include <string>"),
        body = headerBody
    )

    val sourceContent = buildCppSource(
        headerName = "FileTools",
        category = CppFileCategory.TOOLS,
        includes = listOf("#include <fstream>", "#include <sstream>"),
        body = sourceBody
    )

    return CppModelFile(
        name = "FileTools",
        category = CppFileCategory.TOOLS,
        headerContent = headerContent,
        sourceContent = sourceContent
    )
}

